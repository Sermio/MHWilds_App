// Genera lib/utils/asset_ids.g.dart con mapas const id → asset local a partir
// de los nombres en inglés de https://wilds.mhdb.io/en.
// Uso (desde la raíz): dart run scripts/generate_asset_ids.dart
// Volver a ejecutarlo cuando salgan monstruos o mapas nuevos (y sus assets).
import 'dart:convert';
import 'dart:io';

const _base = 'https://wilds.mhdb.io/en';
const _out = 'lib/utils/asset_ids.g.dart';

/// Mismo slug que usaban las pantallas con el nombre de `EnNamesCache`.
String slug(String name) =>
    name.toLowerCase().replaceAll(' ', '_').replaceAll("'", '_');

Future<Map<int, String>> _names(HttpClient client, String endpoint) async {
  final uri = Uri.parse('$_base/$endpoint')
      .replace(queryParameters: {'p': '{"id":true,"name":true}'});
  final res = await (await client.getUrl(uri)).close();
  if (res.statusCode != 200) {
    throw HttpException('$endpoint -> ${res.statusCode}');
  }
  final list =
      jsonDecode(await res.transform(utf8.decoder).join()) as List<dynamic>;
  return {
    for (final e in list.cast<Map<String, dynamic>>())
      e['id'] as int: e['name'] as String,
  };
}

/// id → ruta, solo para los ids cuyo archivo existe; avisa de los que faltan.
Map<int, String> _existing(
    String label, Map<int, String> names, String Function(String) path) {
  final out = <int, String>{};
  names.forEach((id, name) {
    final p = path(slug(name));
    if (File(p).existsSync()) {
      out[id] = p;
    } else {
      stderr.writeln('warning: $label sin asset: $id "$name" ($p)');
    }
  });
  return out;
}

/// id → imágenes de planta `<carpeta>/<carpeta>N.webp` (N = 1, 2, …).
Map<int, List<String>> _maps(Map<int, String> names) {
  final out = <int, List<String>>{};
  names.forEach((id, name) {
    final folder = slug(name);
    final floors = <String>[];
    for (var n = 1;; n++) {
      final p = 'assets/imgs/maps/$folder/$folder$n.webp';
      if (!File(p).existsSync()) break;
      floors.add(p);
    }
    if (floors.isEmpty) {
      stderr.writeln('warning: mapa sin asset: $id "$name" (maps/$folder/)');
    } else {
      out[id] = floors;
    }
  });
  return out;
}

String _sorted<V>(Map<int, V> m, String Function(V) value) {
  final ids = m.keys.toList()..sort();
  return ids.map((id) => '  $id: ${value(m[id] as V)},\n').join();
}

Future<void> main() async {
  final client = HttpClient();
  try {
    final monsters = await _names(client, 'monsters');
    final locations = await _names(client, 'locations');

    final icons = _existing(
        'icono de monstruo', monsters, (s) => 'assets/imgs/monster_icons/$s.webp');
    final images = _existing(
        'imagen de monstruo', monsters, (s) => 'assets/imgs/monsters/$s.webp');
    final maps = _maps(locations);

    String q(String s) => "'$s'";
    File(_out).writeAsStringSync('''
// GENERATED by scripts/generate_asset_ids.dart. Do not edit by hand.
// Regenerate: dart run scripts/generate_asset_ids.dart

/// Monster id → icon in `assets/imgs/monster_icons/`.
const Map<int, String> monsterIconAssets = {
${_sorted(icons, q)}};

/// Monster id → header image in `assets/imgs/monsters/`.
const Map<int, String> monsterImageAssets = {
${_sorted(images, q)}};

/// Location id → floor images in `assets/imgs/maps/<folder>/`, in order.
const Map<int, List<String>> locationMapAssets = {
${_sorted(maps, (List<String> v) => '[${v.map(q).join(', ')}]')}};
''');
    await Process.run('dart', ['format', _out], runInShell: true);
    stdout.writeln('$_out: ${icons.length}/${monsters.length} iconos, '
        '${images.length}/${monsters.length} imágenes, '
        '${maps.length}/${locations.length} mapas');
  } finally {
    client.close();
  }
}
